"""Check, radio-process and encode the driver VO.

  python tools/vo/build.py [--no-check]
For every key in lines.json with a tools/vo/raw/<key>.wav take:
  1. transcribe it with Whisper and flag takes whose words don't match the line (re-run gen.py <key> for those),
  2. bake the radio sound: band-limit, mic drive, compression, carrier hiss and a closing squelch
     (the opening squelch is the game's procedural `radio_squelch`, played by src/vo.js),
  3. encode mono Opus to public/vo/<key>.ogg,
and write src/vo-manifest.js ({ key: [seconds, [levels]] }).
"""
import json, os, re, subprocess, sys
import numpy as np, soundfile as sf
from math import gcd
from scipy.signal import butter, sosfilt, resample_poly

HERE = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(os.path.dirname(HERE))
RAW, OUT = os.path.join(HERE, 'raw'), os.path.join(ROOT, 'public', 'vo')
SR = 48000; LEAD = 0.09   # silence before the voice, where the in-game squelch plays

def load(p):
    x, sr = sf.read(p, always_2d=False)
    if x.ndim > 1: x = x.mean(1)
    if sr != SR: g = gcd(sr, SR); x = resample_poly(x, SR // g, sr // g)
    return x

def trim(x, thr=0.02, pad=0.03):
    idx = np.where(np.abs(x) > thr * np.abs(x).max())[0]
    if not len(idx): return x
    a, b = max(0, idx[0] - int(pad * SR)), min(len(x), idx[-1] + int(pad * 2 * SR))
    return x[a:b]

def bp(x, lo, hi, order=4): return sosfilt(butter(order, [lo, hi], 'bandpass', fs=SR, output='sos'), x)

def comp(x, thr=0.25, ratio=4.0, att=0.003, rel=0.08):
    a, r = np.exp(-1 / (att * SR)), np.exp(-1 / (rel * SR)); env = 0.0; g = np.empty_like(x)
    for i, s in enumerate(np.abs(x)):
        env = a * env + (1 - a) * s if s > env else r * env + (1 - r) * s
        g[i] = 1.0 if env < thr else (thr + (env - thr) / ratio) / env
    return x * g

def radio(x, rng, drive=3.0):
    x = trim(x); x = x / (np.abs(x).max() + 1e-9)
    x = bp(x, 350, 3300)
    x = np.tanh(x * drive) / np.tanh(drive)
    x = bp(x, 300, 3600, 2)
    x = comp(x); x = x / (np.abs(x).max() + 1e-9) * 0.85
    pre, post = int(LEAD * SR), int(0.16 * SR)
    y = np.zeros(pre + len(x) + post); y[pre:pre + len(x)] = x
    t = np.arange(post) / SR
    tail = bp(rng.standard_normal(post), 900, 5000, 2) * np.exp(-t / 0.035) * 0.6
    tail[:40] += np.hanning(80)[:40] * 0.9
    y[pre + len(x):] += tail
    y += bp(rng.standard_normal(len(y)), 1500, 6000, 2) * 0.012 * np.minimum(1, np.arange(len(y)) / (0.02 * SR))
    return np.clip(y, -1, 1).astype(np.float32)

NUM = {'5': 'five', '6': 'six', '12': 'twelve', '50': 'fifty', '1': 'one', '3': 'three', '2': 'two', '4': 'four'}
def words(s):  # Whisper writes numbers as digits and plurals loosely; compare on normalized words
    w = re.findall(r"[a-z0-9']+", s.lower().replace('-', ' '))
    return [NUM.get(x, x).rstrip('s') if len(x) > 3 else NUM.get(x, x) for x in w]

def match(ref, hyp):
    """word recall: fraction of the line's words Whisper heard, plus any extra words it heard."""
    r, h = words(ref), words(hyp)
    extra = len([w for w in h if w not in r])
    hit = sum(1 for w in set(r) if w in h) / max(1, len(set(r)))
    return hit, extra

if __name__ == '__main__':
    check = '--no-check' not in sys.argv
    lines = json.load(open(os.path.join(HERE, 'lines.json')))
    os.makedirs(OUT, exist_ok=True)
    if check:
        from faster_whisper import WhisperModel
        wm = WhisperModel('small.en', device='cpu', compute_type='int8')
    man, bad = {}, []
    for l in lines:
        k = l['key']; src = os.path.join(RAW, k + '.wav')
        if not os.path.exists(src): print('MISSING', k, l['text']); continue
        x = load(src)
        if check:
            a16 = resample_poly(trim(x), 1, 3).astype(np.float32)
            segs, _ = wm.transcribe(a16, beam_size=3, language='en')
            hyp = ' '.join(s.text.strip() for s in segs)
            hit, extra = match(l['text'], hyp)
            if hit < 0.8 or extra > 1: bad.append(k); print(f'CHECK {k} recall={hit:.2f} extra={extra}\n   want: {l["text"]}\n   got:  {hyp}')
        y = radio(x, np.random.default_rng(int(k, 16)))
        tmp = os.path.join(RAW, k + '.radio.wav'); sf.write(tmp, y, SR)
        subprocess.run(['ffmpeg', '-loglevel', 'error', '-y', '-i', tmp, '-ac', '1', '-c:a', 'libopus', '-b:a', '40k',
                        '-application', 'voip', os.path.join(OUT, k + '.ogg')], check=True)
        os.remove(tmp)
        man[k] = [round(len(y) / SR, 2), l['levels']]
    with open(os.path.join(ROOT, 'src', 'vo-manifest.js'), 'w') as f:
        f.write('// Generated by tools/vo/build.py: driver VO clips in public/vo/<key>.ogg, keyed by voKey(subtitle text).\n')
        f.write('// [clip seconds, levels that use it]. Do not edit by hand.\nexport default ' + json.dumps(man, separators=(',', ':')) + ';\n')
    size = sum(os.path.getsize(os.path.join(OUT, k + '.ogg')) for k in man)
    print(f'{len(man)} clips, {size/1024:.0f} KB total; flagged {len(bad)}: {" ".join(bad)}')
